    MOVI R0, 1

MAIN:
    STORE R0, 0xFFFF
    LOAD R1, 0xFF0F
    CMPI R1, 0
    JNZ SPEED_OK
    MOVI R1, 1

SPEED_OK:
    MOVI R3, 40

DELAY_OUTER:
    MOVI R2, 0xFFFF

DELAY_INNER:
    SUBI R2, 1
    JNZ DELAY_INNER
    SUBI R3, 1
    JNZ DELAY_OUTER

SW_SCALE:
    SUBI R1, 1
    JZ SHIFT_LED
    MOVI R3, 40
    JMP DELAY_OUTER

SHIFT_LED:
    SHL R0
    CMPI R0, 0x0100
    JNZ MAIN
    MOVI R0, 1
    JMP MAIN
